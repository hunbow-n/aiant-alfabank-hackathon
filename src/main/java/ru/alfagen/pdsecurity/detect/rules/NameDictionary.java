    private static final Set<String> SURNAME_SUFFIXES = Set.of(
            "ов", "ова", "ев", "ева", "ин", "ина", "ский", "ская", "цкий", "цкая");

    private NameDictionary() {
    }

    public static boolean isFirstName(String normalized) {
        return FIRST_NAMES.contains(normalized);
    }

    public static boolean isPatronymic(String normalized) {
        return PATRONYMICS.contains(normalized);
    }

    /**
     * True if the token looks like a patronymic by suffix: -ич/-овна/-евна/-ична
     * for masculine/feminine forms, plus declined -ичу/-овне/-евне.
     */
    public static boolean looksLikePatronymic(String normalized) {
        return normalized.endsWith("ич") || normalized.endsWith("овна")
                || normalized.endsWith("евна") || normalized.endsWith("ична")
                || normalized.endsWith("ичу") || normalized.endsWith("овне")
                || normalized.endsWith("евне");
    }

    public static boolean looksLikeSurname(String normalized) {
        for (String suffix : SURNAME_SUFFIXES) {
            if (normalized.length() > suffix.length() + 2 && normalized.endsWith(suffix)) {
                return true;
            }
        }
        // Declined forms: dative/genitive/prepositional.
        return normalized.endsWith("ову") || normalized.endsWith("еву")
                || normalized.endsWith("ину") || normalized.endsWith("овым")
                || normalized.endsWith("евым") || normalized.endsWith("иным")
                || normalized.endsWith("овым") || normalized.endsWith("овой")
                || normalized.endsWith("евой") || normalized.endsWith("иной");
    }
